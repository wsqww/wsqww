// 职责:把像素图中指定字符的所有格子合并为一条 rect 路径;参数:map 像素图(字符串数组)、
// cell 单格边长(px)、ox/oy 像素图原点在画布中的偏移、ch 目标字符;
// 返回:path d 字符串(每格一段 M/h/v/h/z 子路径,整体单条 path);副作用:无
export function mapToPath(map, cell, ox, oy, ch) {
  let d = '';
  for (let r = 0; r < map.length; r += 1) {
    for (let c = 0; c < map[r].length; c += 1) {
      if (map[r][c] !== ch) { continue; }
      d += `M${ox + c * cell} ${oy + r * cell}h${cell}v${cell}h-${cell}z`;
    }
  }
  return d;
}
